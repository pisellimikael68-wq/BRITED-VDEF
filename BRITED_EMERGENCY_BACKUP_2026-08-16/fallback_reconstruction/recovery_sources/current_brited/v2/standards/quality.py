QUALITY_STANDARD = """
# OBJECTIF

Chaque contenu BRITED doit :

- être exact ;
- être pédagogique ;
- être utile ;
- être mémorable ;
- être conforme.

L'objectif n'est pas de générer du texte.

L'objectif est de faire progresser le lecteur.

---

# SCORE GLOBAL

Un contenu est évalué sur 100 points.

Les critères sont :

1. Exactitude patrimoniale : 30
2. Pédagogie : 20
3. Intérêt éditorial : 20
4. Adaptation au format : 15
5. Engagement : 15

---

# NIVEAU D'EXIGENCE

Un contenu publié par BRITED doit pouvoir être signé
par un excellent conseiller en gestion de patrimoine.

Aucune approximation importante n'est acceptable.

Chaque phrase doit apporter de la valeur.

Chaque contenu doit permettre au lecteur
de comprendre un mécanisme patrimonial.
"""
